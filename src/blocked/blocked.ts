/**
 * Block page dynamic functionality.
 *
 * Parses URL parameters passed from the blocking redirect and
 * populates the block page with relevant information.
 */

/**
 * Sanitize and format a URL for display.
 * Shows domain + truncated path, hides sensitive query params.
 */
function sanitizeUrl(url: string): string {
  try {
    const parsed = new URL(url);
    const display = parsed.hostname + parsed.pathname;
    // Truncate long paths for display
    const maxLength = 80;
    if (display.length > maxLength) {
      return display.slice(0, maxLength - 3) + '...';
    }
    return display;
  } catch {
    return 'Invalid URL';
  }
}

/**
 * Format a timestamp for display.
 */
function formatTimestamp(ts: number): string {
  const date = new Date(ts);
  // Use ISO format for clarity: YYYY-MM-DD HH:MM:SS UTC
  return date.toISOString().replace('T', ' ').replace(/\.\d{3}Z$/, ' UTC');
}

/**
 * Map internal reason codes to user-friendly category names.
 */
function getCategoryDisplay(reason: string): { label: string; cssClass: string } {
  const categories: Record<string, { label: string; cssClass: string }> = {
    'ioc_match': { label: 'Threat Indicator', cssClass: 'category-default' },
    'phishing': { label: 'Phishing', cssClass: 'category-phishing' },
    'malware': { label: 'Malware', cssClass: 'category-malware' },
    'c2': { label: 'Command & Control', cssClass: 'category-c2' },
  };

  const lower = reason.toLowerCase();
  return categories[lower] || { label: reason, cssClass: 'category-default' };
}

/**
 * Generate a mailto link for false positive reports.
 */
function generateReportLink(blockedUrl: string, timestamp: string, category: string): string {
  const subject = encodeURIComponent('BrowserDefense False Positive Report');
  const body = encodeURIComponent(
    `I believe the following URL was incorrectly blocked:\n\n` +
    `URL: ${blockedUrl}\n` +
    `Time: ${timestamp}\n` +
    `Category: ${category}\n\n` +
    `Reason for false positive:\n[Please describe why you believe this is a false positive]\n\n` +
    `---\nReport generated by BrowserDefense`
  );

  // Default to security team email - organizations can customize this
  return `mailto:security@example.com?subject=${subject}&body=${body}`;
}

/**
 * Initialize the block page.
 */
function init(): void {
  // Parse URL parameters
  const params = new URLSearchParams(window.location.search);
  const blockedUrl = params.get('url') || 'Unknown';
  const reason = params.get('reason') || 'ioc_match';
  const timestamp = params.get('ts');

  // Get DOM elements
  const blockedUrlEl = document.getElementById('blocked-url');
  const timestampEl = document.getElementById('timestamp');
  const categoryEl = document.getElementById('category');
  const categoryRow = document.getElementById('category-row');
  const goBackBtn = document.getElementById('go-back');
  const reportLink = document.getElementById('report-fp') as HTMLAnchorElement | null;

  // Populate blocked URL
  if (blockedUrlEl) {
    blockedUrlEl.textContent = sanitizeUrl(blockedUrl);
  }

  // Populate timestamp
  const ts = timestamp ? parseInt(timestamp, 10) : Date.now();
  const formattedTime = formatTimestamp(ts);
  if (timestampEl) {
    timestampEl.textContent = formattedTime;
  }

  // Populate category with badge styling
  const { label, cssClass } = getCategoryDisplay(reason);
  if (categoryEl && categoryRow) {
    categoryEl.textContent = label;
    categoryEl.classList.add('category-badge', cssClass);
  }

  // Set up Go Back button
  if (goBackBtn) {
    goBackBtn.addEventListener('click', () => {
      // Go back in history, or close tab if no history
      if (window.history.length > 1) {
        window.history.back();
      } else {
        window.close();
      }
    });
  }

  // Set up Report False Positive link
  if (reportLink) {
    reportLink.href = generateReportLink(blockedUrl, formattedTime, label);
  }
}

// Initialize when DOM is ready
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', init);
} else {
  init();
}

