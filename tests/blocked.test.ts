/**
 * Tests for the block page functionality.
 */
import { describe, it, expect } from 'vitest';

// Import functions by re-implementing them here for testing
// (the actual blocked.ts runs in browser context with DOM)

function sanitizeUrl(url: string): string {
  try {
    const parsed = new URL(url);
    const display = parsed.hostname + parsed.pathname;
    const maxLength = 80;
    if (display.length > maxLength) {
      return display.slice(0, maxLength - 3) + '...';
    }
    return display;
  } catch {
    return 'Invalid URL';
  }
}

function formatTimestamp(ts: number): string {
  const date = new Date(ts);
  return date.toISOString().replace('T', ' ').replace(/\.\d{3}Z$/, ' UTC');
}

function getCategoryDisplay(reason: string): { label: string; cssClass: string } {
  const categories: Record<string, { label: string; cssClass: string }> = {
    'ioc_match': { label: 'Threat Indicator', cssClass: 'category-default' },
    'phishing': { label: 'Phishing', cssClass: 'category-phishing' },
    'malware': { label: 'Malware', cssClass: 'category-malware' },
    'c2': { label: 'Command & Control', cssClass: 'category-c2' },
  };

  const lower = reason.toLowerCase();
  return categories[lower] || { label: reason, cssClass: 'category-default' };
}

function generateReportLink(blockedUrl: string, timestamp: string, category: string): string {
  const subject = encodeURIComponent('BrowserDefense False Positive Report');
  const body = encodeURIComponent(
    `I believe the following URL was incorrectly blocked:\n\n` +
    `URL: ${blockedUrl}\n` +
    `Time: ${timestamp}\n` +
    `Category: ${category}\n\n` +
    `Reason for false positive:\n[Please describe why you believe this is a false positive]\n\n` +
    `---\nReport generated by BrowserDefense`
  );

  return `mailto:security@example.com?subject=${subject}&body=${body}`;
}

describe('Block Page', () => {
  describe('sanitizeUrl', () => {
    it('should extract hostname and pathname from URL', () => {
      expect(sanitizeUrl('https://evil.com/phishing/login')).toBe('evil.com/phishing/login');
    });

    it('should strip query parameters', () => {
      expect(sanitizeUrl('https://evil.com/page?token=secret')).toBe('evil.com/page');
    });

    it('should strip hash fragments', () => {
      expect(sanitizeUrl('https://evil.com/page#section')).toBe('evil.com/page');
    });

    it('should truncate long URLs', () => {
      const longPath = '/a'.repeat(100);
      const result = sanitizeUrl(`https://evil.com${longPath}`);
      expect(result.length).toBe(80);
      expect(result.endsWith('...')).toBe(true);
    });

    it('should return Invalid URL for malformed URLs', () => {
      expect(sanitizeUrl('not-a-url')).toBe('Invalid URL');
    });

    it('should handle URLs with just hostname', () => {
      expect(sanitizeUrl('https://example.com')).toBe('example.com/');
    });
  });

  describe('formatTimestamp', () => {
    it('should format timestamp in UTC ISO format', () => {
      const ts = Date.UTC(2026, 0, 9, 8, 15, 23);
      const result = formatTimestamp(ts);
      expect(result).toBe('2026-01-09 08:15:23 UTC');
    });

    it('should handle current timestamp', () => {
      const result = formatTimestamp(Date.now());
      expect(result).toMatch(/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} UTC$/);
    });
  });

  describe('getCategoryDisplay', () => {
    it('should map ioc_match to Threat Indicator', () => {
      const result = getCategoryDisplay('ioc_match');
      expect(result.label).toBe('Threat Indicator');
      expect(result.cssClass).toBe('category-default');
    });

    it('should map phishing category', () => {
      const result = getCategoryDisplay('phishing');
      expect(result.label).toBe('Phishing');
      expect(result.cssClass).toBe('category-phishing');
    });

    it('should map malware category', () => {
      const result = getCategoryDisplay('malware');
      expect(result.label).toBe('Malware');
      expect(result.cssClass).toBe('category-malware');
    });

    it('should map c2 category', () => {
      const result = getCategoryDisplay('c2');
      expect(result.label).toBe('Command & Control');
      expect(result.cssClass).toBe('category-c2');
    });

    it('should be case insensitive', () => {
      expect(getCategoryDisplay('PHISHING').label).toBe('Phishing');
      expect(getCategoryDisplay('Malware').label).toBe('Malware');
    });

    it('should return original string for unknown categories', () => {
      const result = getCategoryDisplay('custom_category');
      expect(result.label).toBe('custom_category');
      expect(result.cssClass).toBe('category-default');
    });
  });

  describe('generateReportLink', () => {
    it('should generate a mailto link', () => {
      const result = generateReportLink('https://evil.com', '2026-01-09 08:15:23 UTC', 'Phishing');
      expect(result.startsWith('mailto:security@example.com?')).toBe(true);
    });

    it('should include subject', () => {
      const result = generateReportLink('https://evil.com', '2026-01-09', 'Phishing');
      expect(result).toContain('subject=BrowserDefense%20False%20Positive%20Report');
    });

    it('should include blocked URL in body', () => {
      const result = generateReportLink('https://evil.com/path', '2026-01-09', 'Phishing');
      expect(result).toContain('https%3A%2F%2Fevil.com%2Fpath');
    });

    it('should include timestamp in body', () => {
      const result = generateReportLink('https://evil.com', '2026-01-09 08:15:23 UTC', 'Phishing');
      expect(result).toContain('2026-01-09%2008%3A15%3A23%20UTC');
    });

    it('should include category in body', () => {
      const result = generateReportLink('https://evil.com', '2026-01-09', 'Malware');
      expect(result).toContain('Malware');
    });
  });
});
